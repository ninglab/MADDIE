"""
Lead optimizer usage examples.

Run one local toy example:
    python -m lead_optimizer.example

Run the full HPC example with an LLM planner and GeLLMO-C as the tool:
    python -m lead_optimizer.example --hpc
"""

import argparse
import os
from pathlib import Path
import sys
from tempfile import TemporaryDirectory

from lead_optimizer import LeadOptimizerAgent
from lead_optimizer.llms import HFLocalLLM
from lead_optimizer.planner import JSONPlanner
from lead_optimizer.tools import GeLLMOOptimizerTool


TOY_PROMPT = "Please optimize the QED of molecules in smiles.csv"

HPC_PROMPT = (
    "Please optimize the molecules in sample.csv by increasing DRD2 inhibition "
    "to <THRESHOLD> 0.25 </THRESHOLD> and penalized logP to "
    "<THRESHOLD> 1.7 </THRESHOLD> while keeping QED unchanged."
)


def write_toy_csv(path: Path) -> None:
    path.write_text(
        "smiles\n"
        "CCO\n"
        "CCN\n"
    )


def write_hpc_csv(path: Path) -> None:
    path.write_text(
        "id,smiles\n"
        "aspirin_like,CC(=O)Oc1ccccc1C(=O)O\n"
        "drd2_seed,N#Cc1ccc(cc1)N(CCCl)CCCl\n"
    )


def print_run(env: Path, response: str, metadata: dict) -> None:
    output_csv = Path(metadata["outputs"]["csv"])

    print(f"Environment: {env}")
    print(f"Response   : {response}")
    print(f"Output CSV : {output_csv}")
    print("\nMetadata:")
    print(metadata)
    print("\nOutput contents:")
    print(output_csv.read_text())


def run_toy_example() -> None:
    print("=" * 60)
    print("Toy example: LeadOptimizerAgent.run(prompt, path_to_env)")
    print("=" * 60)

    with TemporaryDirectory() as tmpdir:
        env = Path(tmpdir)
        write_toy_csv(env / "smiles.csv")

        response, metadata = LeadOptimizerAgent(num_outputs=2).run(
            prompt=TOY_PROMPT,
            path_to_env=str(env),
        )

        print(f"Prompt     : {TOY_PROMPT}")
        print_run(env, response, metadata)


def run_hpc_gellmo_example(args: argparse.Namespace) -> None:
    print("\n" + "=" * 60)
    print("HPC example: LLM planner + GeLLMO-C tool")
    print("=" * 60)

    gellmo_repo = Path(args.gellmo_repo).resolve()
    if str(gellmo_repo) not in sys.path:
        sys.path.insert(0, str(gellmo_repo))

    old_cwd = Path.cwd()
    os.chdir(gellmo_repo)
    try:
        # GeLLMOTool imports config.py, prompter.py, and templates from the
        # GeLLMO-C repo, so import after adding/changing into that repo.
        from lead_optimizer.tools.gellmo import GeLLMOTool

        # Agent brain/planner: an HF instruct model returns the JSON plan.
        planner_llm = HFLocalLLM(
            model_name=args.planner_model,
            max_new_tokens=args.planner_max_new_tokens,
            temperature=0.0,
        )
        planner = JSONPlanner(planner_llm)

        # Tool: GeLLMO-C does the molecule optimization after planning.
        gellmo = GeLLMOTool(
            base_model=args.gellmo_base_model,
            lora_weights=args.gellmo_lora_weights,
        )
        optimization_tool = GeLLMOOptimizerTool(gellmo)

        agent = LeadOptimizerAgent(
            planner=planner,
            tool=optimization_tool,
            num_outputs=args.num_outputs,
        )

        with TemporaryDirectory() as tmpdir:
            env = Path(tmpdir)
            input_dir = env / "input"
            input_dir.mkdir()
            write_hpc_csv(input_dir / "sample.csv")

            response, metadata = agent.run(
                prompt=HPC_PROMPT,
                path_to_env=str(env),
            )

            print(f"Prompt       : {HPC_PROMPT}")
            print(f"Agent brain  : JSONPlanner({args.planner_model})")
            print(f"Tool         : {optimization_tool.name}")
            print(f"GeLLMO repo  : {gellmo_repo}")
            print_run(env, response, metadata)
    finally:
        os.chdir(old_cwd)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Run lead optimizer examples.")
    parser.add_argument(
        "--hpc",
        action="store_true",
        help="Run the full HPC example with an LLM planner and GeLLMO-C tool.",
    )
    parser.add_argument(
        "--planner-model",
        default="/path/to/models/llama31_8b_instruct",
        help="Hugging Face model path used by JSONPlanner.",
    )
    parser.add_argument(
        "--planner-max-new-tokens",
        type=int,
        default=120,
        help="Maximum new tokens generated by the planner model.",
    )
    parser.add_argument(
        "--gellmo-repo",
        default="/path/to/GeLLMO-C",
        help="Path to the GeLLMO-C repository.",
    )
    parser.add_argument(
        "--gellmo-base-model",
        default="/path/to/models/llama31_8b_instruct",
        help="Base model path passed to GeLLMO-C.",
    )
    parser.add_argument(
        "--gellmo-lora-weights",
        default="/path/to/models/gellmo_c_p10_llama_lora",
        help="LoRA weights path passed to GeLLMO-C.",
    )
    parser.add_argument(
        "--num-outputs",
        type=int,
        default=3,
        help="Number of optimized candidates per input molecule for GeLLMO-C.",
    )
    return parser.parse_args()


if __name__ == "__main__":
    parsed_args = parse_args()
    run_toy_example()
    if parsed_args.hpc:
        run_hpc_gellmo_example(parsed_args)
